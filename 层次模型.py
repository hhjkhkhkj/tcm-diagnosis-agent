# -*- coding: utf-8 -*-
"""因子重要性层次 —— 组装成一份可读的「判决因子层次」文档

## 层次是两层，来源不同（这条是关键，别混）

    门控层  = 决定「是哪一经 / 哪个场景」的因子   ← **数据算出来的**（互信息、逐经剖面）
    修饰层  = 选定经之后才起加减作用的药对规则     ← **书上印着的**（`药对` 表，可举证）

**为什么是这个分工**：书里只印了「药对 ↔ 证候」这种局部规则，
「哪条规则更管用」书上一个字没写。反过来，数据能比较因子之间的判别力，
但**写不出医家的组方逻辑**。所以：**结构照抄，强弱靠数据验。**

## 这份文档是什么，不是什么（写在最前面）

它是**库的画像** —— 描述你这 1000 例里「哪些因子跟哪一经沾边、沾多少」。
它**不是判别器**：不能拿它预测一个新病人该归哪一经，因为
① Y 只有 157 案（按经分完每份 2~60 案）
② 这些因子是从同一批案子里抽的，用它自评等于自己拟合自己
③ 完全没有「有效/无效」的对照。

用法：`py _层次模型.py`
"""
import os
import sqlite3
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(HERE, "中医大脑医案库.db")
sys.path.insert(0, HERE)

import 因子分析 as A   # noqa: E402

经序 = ["太阳", "阳明", "少阳", "太阴", "少阴", "厥阴"]
经义 = {"太阳": "表（阳）", "阳明": "里（热实）", "少阳": "半表半里",
        "太阴": "里（虚寒·脾）", "少阴": "里（虚寒·心肾）", "厥阴": "里（寒热错杂）"}


def 药对层(con, topn=18):
    """修饰层：书里的「药对 ↔ 证候」规则。**这是抄的，不是算的**"""
    出 = []
    for r in con.execute("SELECT 名,主治,应用,次数 FROM 药对 ORDER BY 次数 DESC, 名"):
        出.append({"药对": r[0], "主治": (r[1] or "").strip(),
                   "应用": (r[2] or "").strip(), "次数": r[3]})
        if len(出) >= topn:
            break
    return 出


def main():
    案因子, 案经, 词频 = A.取()
    剖, 各经案, 全体率 = A.六经剖面(案因子, 案经, 词频)
    mi = A.互信息(案因子, 案经, 词频, 各经案)
    共 = A.共现(案因子, 词频, 上限=15, 门槛=10)
    con = sqlite3.connect(DB)
    药对 = 药对层(con)
    主 = A.主经(案经)
    案数 = Counter(主.values())
    太阴推断 = con.execute("SELECT COUNT(*) FROM 医案因子"
                          " WHERE 维度='六经' AND 因子='太阴' AND 来源='模型推断'").fetchone()[0]
    con.close()

    p = os.path.join(HERE, "因子重要性层次.md")
    with open(p, "w", encoding="utf-8") as w:
        w.write("# 中医大脑 · 因子重要性层次\n\n")
        w.write(A.指纹行())
        w.write("\n")
        w.write("生成：`py _层次模型.py`　｜　数据：%d 案有标签 / %d 个 ≥5 次因子 / 原文六经 %d 案\n\n"
                % (len(案因子), len([f for f, c in 词频.items() if c >= 5]), len(案经)))

        w.write("## 〇、这份文档是什么，不是什么\n\n")
        w.write("**是**：库的画像 —— 描述这 1000 例里，哪些因子跟哪一经沾边、沾多少。\n\n")
        w.write("**不是**判别器。三条硬边界：\n\n")
        w.write("1. **Y 太薄** —— 只有 %d 案「原文写了六经」，按经分完每份如下表，"
                "少阴/阳明各几十案，厥阴只剩个位数。样本量撑不起「预测」。\n" % len(案经))
        w.write("2. **自己拟合自己** —— 这些因子是从同一批案子里抽出来的，"
                "拿它自评等于用同一份数据出题又答题。\n")
        w.write("3. **没有对照** —— 书里全是治好的案例，没有「无效」这一半。"
                "所以**任何数字都是描述性的，不是效应量**。\n\n")

        w.write("## 一、Y 的样本量（先看这个，再看任何结论）\n\n")
        w.write("| 经 | 含义 | 案数 |\n|---|---|---|\n")
        for 经 in 经序:
            n = 案数.get(经, 0)
            标 = " ⚠️ 太少" if 0 < n < 15 else (" ❌ 无" if n == 0 else "")
            w.write("| %s | %s | %d%s |\n" % (经, 经义[经], n, 标))
        w.write("\n> 太阴在原文批里**一条都没有** —— 它的 %d 条全在「模型推断」批里，"
                "而推断批不能当 Y（那是模型自己的想法，不是医案说的）。\n\n" % 太阴推断)

        w.write("## 二、门控层 —— 决定「是哪一经」的因子\n\n")
        w.write("判据：**互信息 I(因子;经)**。怎么读它 —— 想象不看任何信息时你只能瞎猜，"
                "互信息就是「知道这条因子后，猜对的把握增加了多少」。0 = 完全没用。\n\n")
        w.write("⚠️ 下面每张表都要连着案数一起看。**案数 < 20 的经，排名是靠噪声撑的**，"
                "别当真规律。\n\n")
        for 经 in 经序:
            if 经 not in mi:
                continue
            # ⚠️ 只留「该经里出现 ≥3 次」的 —— 某条因子在一类里只出现 1 次时，
            #    互信息会算出个虚高值（1/30 也能排到第一），那是小样本假象不是规律。
            行 = [x for x in mi[经] if x[1] >= 3]
            if not 行:
                w.write("### %s（%d 案）\n\n"
                        "**没有因子达到「该经内出现 ≥3 次」—— 样本太少，算不出可信排名。**\n\n"
                        % (经, 案数.get(经, 0)))
                continue
            w.write("### %s（%d 案）\n\n" % (经, 案数.get(经, 0)))
            w.write("| 因子 | 该经里有 | 该经里没有 | 互信息 |\n|---|---|---|---|\n")
            for f, a, c, v in 行[:10]:
                w.write("| %s | %d | %d | %.4f |\n" % (f, a, c, v))
            w.write("\n")
        w.write("### 逐经「最反常」的因子（出现率比全体高多少倍）\n\n")
        for 经 in 经序:
            if 经 not in 剖:
                continue
            w.write("**%s**：%s\n\n" % (经, "　".join(
                "%s(×%.1f)" % (f, lift) for f, n, r, lift in 剖[经]["行"][:6]
                if n >= 3)))
        w.write("\n> 只列该经里出现 ≥3 次的 —— 出现一两次的「×7 倍」是假象，不是规律。\n\n")

        w.write("## 三、共现结构 —— 哪些因子天然抱团\n\n")
        w.write("不预测、不分组，只看**哪两条因子反复一起出现**（Jaccard = 同现÷至少有一条）。\n\n")
        w.write("| 因子甲 | 因子乙 | 同现案数 | Jaccard |\n|---|---|---|---|\n")
        for x, y, n, j in 共:
            w.write("| %s | %s | %d | %.3f |\n" % (x, y, n, j))
        w.write("\n**为什么这个有用**：教科书判据失效（见 `_判据验证.md`，7 条里 5 条一条都命中不了），"
                "因为「完整三联症」临床上很少出现。这张表列的是**实际反复出现的组合**——"
                "库里真正在说的话。\n\n")

        w.write("## 四、修饰层 —— 选定经之后才起作用的加减\n\n")
        w.write("**这一层是抄的，不是算的。** 来源：书里的 `药对` 表（药对 → 主治 → 应用），"
                "按库内出现次数排。\n\n")
        w.write("注意：「应用」栏写的证候是**书上原话**，可追回页码——这是它的价值，"
                "也是它的限度（书上没写这些规则各有多管用）。\n\n")
        w.write("| 药对 | 库内次数 | 主治 | 应用（书里原话，节选） |\n|---|---|---|---|\n")
        for d in 药对:
            w.write("| **%s** | %d | %s | %s |\n"
                    % (d["药对"], d["次数"], d["主治"][:40], d["应用"][:80]))
        w.write("\n")

        w.write("## 五、怎么用 / 别怎么用\n\n")
        w.write("**能用**\n\n")
        w.write("- 当**检索的排序依据**：门控层排名靠前的因子，在面板「查」里值得优先勾\n")
        w.write("- 当**解释的素材**：说清「为什么指向少阳」时，可以引共现表和判别因子\n")
        w.write("- 当**怀疑的清单**：某条结论落在案数 < 20 的经上，就该多打一个问号\n\n")
        w.write("**别用**\n\n")
        w.write("- ❌ **别当权重** —— 互信息大 ≠ 「这个因子对诊断贡献几成」，它只说「有信息量」\n")
        w.write("- ❌ **别当疗效** —— 这些数字里没有一个字涉及「治好了没有」\n")
        w.write("- ❌ **别当处方依据** —— 修饰层是书里的规则，\"书里有\"≠\"对这个人对\"\n\n")
        w.write("**唯一能让这些变成「真判断」的路**：接诊时存进面板「我的病案」，"
                "14 天后回访填效果。攒到几百条带随访的记录，"
                "「哪些症状指向哪个**有效**方」才有第一个真答案。\n")
    print("写了 %s" % os.path.basename(p))
    print("  经样本：%s" % dict(案数))
    print("  门控层算了 %d 经 ／ 共现 %d 对 ／ 修饰层 %d 条药对"
          % (len(mi), len(共), len(药对)))


if __name__ == "__main__":
    main()
