# -*- coding: utf-8 -*-
"""修 `关键词路由.目标id` —— 让它指向"真正讲这件事的那块"，不是文件头的 52 字空壳

## 为什么要修

`_抽文献块2.py` 回填 `目标id` 时，用的是：

    SELECT id FROM 文献块 WHERE 出处 LIKE 前缀||'%' LIMIT 1     ← **取该文件的第一块**

而每个 md 文件的**第一块是文件头的残片**（标题空、50 字上下）。实测：

    路由「胸痹/胸闷/心痛/胸背痛」→ 目标id 868 = 52 字空壳
    同一文件里真正讲胸痹的是  id880「胸痹心痛短气病脉证并治第九」1524 字

**所以 32 条进文献块的路由，指的几乎全是空壳。** 路由是通的（不再死链），
但通到了墙上 —— 「死链」变「活链指向空处」，比死链更难发现。

## 怎么修

对每条 `目标表='文献块'` 的路由：把它自己那串关键词（`胸痹/胸闷/心痛/胸背痛`）
拿去**逐块比对该文件下所有块的标题**，命中最多者胜；标题一条都不中的，
退到该文件最大的那块（并标出来让人复查）。

⚠️ 只动 `目标表='文献块'` 的。另外五张表（医案/针灸处方/六经/本草/剂量_规范）
的目标id 有各自的含义，**不在这次范围内**，别一起改。
"""
import os
import re
import sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(HERE, "中医大脑医案库.db")
最小字数 = 80          # 低于这个的是文件头碎块，不配当目标


def main():
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row

    改, 没动, 退化 = [], [], []
    for r in con.execute("SELECT id,关键词,原文路径,目标id,出处 FROM 关键词路由 "
                         "WHERE 目标表='文献块' ORDER BY id"):
        路 = re.sub(r"#.*$", "", (r["原文路径"] or "")).strip()
        if not 路:
            没动.append((r["id"], r["关键词"], "没有原文路径"))
            continue
        块 = [dict(x) for x in con.execute(
            "SELECT id,标题,正文,字数 FROM 文献块 WHERE 出处 LIKE ? ORDER BY id", (路 + "%",))]
        if not 块:
            没动.append((r["id"], r["关键词"], "这个文件在文献块里找不到：%s" % 路))
            continue
        # 路由自己的关键词串：『胸痹/胸闷/心痛/胸背痛』→ ['胸痹','胸闷','心痛','胸背痛']
        词 = [t.strip() for t in re.split(r"[/／、,，]", r["关键词"] or "") if t.strip()]
        候选 = [b for b in 块 if (b["字数"] or 0) >= 最小字数] or 块
        # ⚠️ **标题和正文都要算**。只看标题会漏掉一大片：路由用的是**症名**
        # （『水肿/风水/皮水/正水/石水』），而金匮的章名是**『水气病脉证并治第十五』** ——
        # 标题永远对不上，可正文里全是这几个词。只比标题时这一条会退化到"取最大块"。
        # 标题命中是强证据（这章就叫这名），正文命中是弱证据，所以给 10 倍权重。
        #
        # ⚠️ 再加一条**章名优先**。不加会指错：『水肿/风水/皮水/正水/石水』这一条，
        # 得分最高的是 `枳实白术汤方`（5688 字，正文命中 4 词），
        # 那块看着是"枳实白术汤"，**其实是切块时把整章并进去了、标题取了里面第一个方名**。
        # 而真正讲水气病的章 `水气病脉证并治第十五` 只命中 2 词，排在后面。
        # → 标题里有「脉证并治/病脉证」的，才是**章**；标题是「××汤方」的是**方**。
        #   路由问的是"该去哪一章读"，所以章块必须压过方块。
        最好, 得分 = None, 0
        for b in 候选:
            题 = b["标题"] or ""
            正 = b["正文"] or ""
            基 = (sum(1 for t in 词 if t and t in 题) * 10
                  + sum(1 for t in 词 if t and t not in 题 and t in 正) * 3)
            # ⚠️ 章名加分**只能用来裁决同分，不能单独得分**。
            # 让它单独得分的话，`倪海厦内经讲解` 这种**标签型关键词**（一个词都中不了）
            # 会靠"标题里有脉证并治"白拿 50 分，指到某个**看着合理其实随机**的章 ——
            # 那比指最大块更糟，因为它看起来像是有依据的。
            # 一个字都没中的块，就是跟这条路由无关，加分救不了它。
            if 基 == 0:
                continue
            s = 基 + (40 if re.search(r"脉证并治|病脉证|脉证治", 题) else 0)
            if s > 得分:
                最好, 得分 = b, s
        if 最好 is None:                       # 标题正文都没中 → 退到最大的那块
            最好 = max(候选, key=lambda b: b["字数"] or 0)
            退化.append((r["id"], r["关键词"], 最好["标题"], 最好["字数"]))
            # ⚠️ 这些的关键词是**标签**（「倪海厦内经讲解」），不是词表 —— 逐块比对**原理上就中不了**。
            # 所以标在出处里：消费者看见这行就知道「目标其实是整个文件，id 只用来定位文件」，
            # 别把它当成"这块就是讲这个的"。**宁可标明是文件级，也不要一个看着对其实是随机的块 id。**
            if "目标为整文件" not in (r["出处"] or ""):     # 幂等：标记只加一次
                con.execute("UPDATE 关键词路由 SET 出处=? WHERE id=?",
                            ("%s ｜ ⚠️目标为整文件（关键词是标签不是词表，逐块比对中不了；"
                             "id 取该文件最大块，仅供定位文件）" % (r["出处"] or ""), r["id"]))
        if 最好["id"] != r["目标id"]:
            con.execute("UPDATE 关键词路由 SET 目标id=? WHERE id=?", (最好["id"], r["id"]))
            改.append((r["id"], r["关键词"], r["目标id"], 最好["id"],
                       (最好["标题"] or "（无标题）")[:30], 最好["字数"], 得分))
        else:
            没动.append((r["id"], r["关键词"], "本来就对：%s" % (最好["标题"] or "")[:24]))
        # 这一条**这次匹配上了** → 把上一轮可能留下的「整文件级」标记撤掉，否则标记会说谎
        if "目标为整文件" in (r["出处"] or ""):
            con.execute("UPDATE 关键词路由 SET 出处=? WHERE id=?",
                        (re.sub(r"\s*｜\s*⚠️目标为整文件.*$", "", r["出处"]), r["id"]))
    con.commit()

    print("=== 改了 %d 条 ===" % len(改))
    for i, 词, 旧, 新, 标, 字, 分 in 改:
        print("  #%-3d %-24s %s → %-5s %s（%d字，标题命中%d）"
              % (i, 词[:22], 旧, 新, 标, 字, 分))
    print("\n=== 没动 %d 条 ===" % len(没动))
    for i, 词, 因 in 没动:
        print("  #%-3d %-24s %s" % (i, (词 or "")[:22], 因))
    if 退化:
        print("\n=== ⚠️ 标题正文都没中、退到最大块（这 %d 条已在出处里标明是「整文件级」）===" % len(退化))
        for i, 词, 标, 字 in 退化:
            print("  #%-3d %-24s → %s（%d字）" % (i, (词 or "")[:22], (标 or "（无标题）")[:26], 字))

    print("\n=== 复查：还剩多少条指向 <80 字的空壳 ===")
    坏 = con.execute(
        "SELECT COUNT(*) FROM 关键词路由 k JOIN 文献块 w ON w.id=k.目标id"
        " WHERE k.目标表='文献块' AND w.字数 < ?", (最小字数,)).fetchone()[0]
    print("   %d 条（改之前是 32 条里的大多数）" % 坏)
    con.close()


if __name__ == "__main__":
    main()
