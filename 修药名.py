def main():
    con = sqlite3.connect(DB)
    # 只加不删：留一列存原样，随时能回滚
    try:
        con.execute("ALTER TABLE 处方 ADD COLUMN 药_原始 TEXT")
    except Exception:
        pass

    # 1) 处方
    改 = 0
    名计 = defaultdict(int)
    for 药 in [r[0] for r in con.execute("SELECT DISTINCT 药 FROM 处方")]:
        新 = 药名.get((药 or "").strip())
        if 新:
            名计[药] = con.execute("SELECT COUNT(*) FROM 处方 WHERE 药=?", (药,)).fetchone()[0]
            con.execute(
                "UPDATE 处方 SET 药_原始 = COALESCE(药_原始, 药), 药=? WHERE 药=?", (新, 药))
            改 += 名计[药]
    con.commit()

    # 2) 剂量分布（从处方算出来的，跟着改；同一药合并时要并次数）
    #    直接改药名，然后按新名合并（出现次数相加）
    行 = list(con.execute("SELECT 药,出现次数,最小,中位,最大,均值,source,单位 FROM 剂量分布"))
    并 = {}
    for 药, 次, 小, 中, 大, 均, src, 单 in 行:
        新 = 药名.get((药 or "").strip(), 药)
        k = (新, src)
        if k in 并:
            旧 = 并[k]
            并[k] = [新, 旧[1] + 次, min(旧[2], 小), 旧[3], max(旧[4], 大), 旧[5], src, 单]
        else:
            并[k] = [新, 次, 小, 中, 大, 均, src, 单]
    con.execute("DELETE FROM 剂量分布")
    con.executemany("INSERT INTO 剂量分布(药,出现次数,最小,中位,最大,均值,source,单位)"
                    " VALUES(?,?,?,?,?,?,?,?)", list(并.values()))
    con.commit()

    print("处方：改了 %d 行，涉及 %d 个错名" % (改, len(名计)))
    for 错, n in sorted(名计.items(), key=lambda x: -x[1]):
        print("   %-8s → %-8s  %d 行" % (错, 药名[错], n))
    print()
    print("剂量分布：%d 行 → %d 行（合并了同名）" % (len(行), len(并)))

    # 3) `药对` 表的名 —— 药对名是「药+药」拼的，逐个成分归一。
    #    **这张表是候选方反推的底座**：名字里带错字，那条药对就永远匹配不上。
    对特例 = {"白术十人参": "白术+人参"}      # 「十」是「+」被读错
    改对 = 0
    for (名,) in list(con.execute("SELECT 名 FROM 药对")):
        # 「十」被当成分隔符「+」用了 —— 它可能出现在名中间（干姜+白术十人参），
        # 所以整条先换，别只匹配整名
        基 = 名.replace("十", "+")
        新 = "+".join(药名.get(x.strip(), x.strip()) for x in 基.split("+"))
        if 新 != 名:
            con.execute("UPDATE 药对 SET 名=? WHERE 名=?", (新, 名))
            改对 += 1
    con.commit()
    print("药对：改了 %d 条名" % 改对)
    print()
    还脏 = [r[0] for r in con.execute("SELECT 药 FROM 剂量分布 WHERE LENGTH(药)>5")]
    print("仍存疑、没动的：%s" % "、".join(存疑))
    print("   出现超过 5 字的药名（可能有漏网）：%s" % ("、".join(还脏) or "无"))
    con.close()


if __name__ == "__main__":
    main()
