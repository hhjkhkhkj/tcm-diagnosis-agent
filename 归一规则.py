# ============ 通用工具 ============
def 归一药(名):
    return 药名.get(名, 名)


def 归一标签(名):
    if 名 in 标签丢弃:
        return None
    return 标签.get(名, 名)


def 归一基础方(名):
    return 方名.get(名, 名)


def 归一合方(名):
    """把「A合B」按基础方归一，并统一合方顺序（A合B == B合A）"""
    import re
    s = re.sub(r"[\[\]【】\s]", "", 名 or "")
    s = re.sub(r"[，。、；].*$", "", s)
    if "组方" in s:
        return None
    parts = [归一基础方(p.strip()) for p in s.split("合")]
    parts = [p for p in parts if p and p not in 方名丢弃]
    return "合".join(sorted(parts)) if parts else None


def 药对名(名):
    """药对名 = 药+药+…，逐味归一；不是纯药名的整条丢掉（正文混进来了）"""
    import re
    s = re.sub(r"\s+", "", 名 or "")
    parts = [归一药(p) for p in s.split("+")]
    parts = [p for p in parts if re.fullmatch(r"[一-鿿]{2,5}", p or "")]
    if len(parts) < 2:
        return None
    return "+".join(parts)


