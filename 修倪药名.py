"""修 `处方` 表里**倪海厦那批**的药名（source='倪海厦'），然后重建 `剂量_观测_倪`

## 为什么

`剂量_观测_倪`（346 味）**建在沙滩上** —— 它是从 `处方 WHERE source='倪海厦'` 直接统计的，
而那 7787 行 / 362 个药名**从来没归过一**。实测里面有：

    58 个长度 ≥4 的**整句**：`方加當歸`/`改炮附子為`/`重用桔梗`/`患者較嬌小故用`/`所以可以加重到`
    30 个**单字截断**：`辛(8)`/`芍(7)`/`草(6)`/`黃(4)`
    约 50 个 2~3 字的残渣：`加半夏(4)`/`減為(2)`/`每日(2)`/`原來(1)`/`一罐(1)`
    外加大量**繁简 & OCR 重复**：當歸/当归、白朮/白术、乾薑/亁薑/幹薑/乾姜、玉金=鬱金、淮山=山藥…

**为什么要紧**：提示词里写着「剂量参照**库里的分布**」「轻证→**倪海厦经方常规剂量**」。
模型看不到倪的剂量 → 它被要求按倪的档给量却看不到数。可要是**原样接上**，
它会输出「變多 10g」「重用桔梗 3錢」这种东西 —— 比不接更坏。
（对照：`_修药名.py` 当时说"认不出的 8 味留着不动" —— 那对 `处方`（原始数据、要留痕）
是对的，对 `剂量分布`（**派生统计表、模型直接读**）是错的。）

## 做法

1. **剥连接词**：`方加當歸`→`當歸`、`重用桔梗`→`桔梗`、`改白芍為`→`白芍`
2. **opencc 繁→简**：當歸→当归、白朮→白术 …
3. **手工映射**：OCR 变体与简称（玉金→郁金、淮山→山药、牡蛎的错字…）
4. **白名单核对**：结果必须落在 问止 85 味 ∪ 本草 453 药名 ∪ 常用药补表 里
5. **落不进的 → 不写**（不猜）。`处方` 里原值记进 `药_原始` 留痕，可回滚。

幂等：只处理 `药_原始 IS NULL` 的倪案行；重建 `剂量_观测_倪` 全删全插。
"""
