def 繁简():
    try:
        import opencc
        return opencc.OpenCC("t2s").convert
    except Exception:
        return lambda s: s


def 剥词(名):
    """把『方加當歸』『改白芍為』这类整句剥成药名

    ⚠️ 药名夹在中间的要**捕获**，不能用 `改.*?為` 整条删掉 ——
    那样连药名一起吃掉，`改白芍為` 会变成空串。（第一版就是这个毛病。）
    """
    s = 名.strip()
    for 模, 替 in [
        (r"^方?改(.+?)為$", r"\1"),          # 改白芍為 → 白芍
        (r"^加重(.+?)由.*$", r"\1"),         # 加重乾薑由二改 → 乾薑
        (r"^粒加(.+)$", r"\1"),              # 粒加芒硝 → 芒硝
        (r"^前各半碗加(.+)$", r"\1"),
        (r"^方加(.+)$", r"\1"),              # 方加當歸 → 當歸
        (r"^同前方加(.+)$", r"\1"),
        (r"^日方加(.+)$", r"\1"),
        (r"^前方加(.+)$", r"\1"),
        (r"^故重用?(.+?)(?:至)?$", r"\1"),    # 重用桔梗 → 桔梗 / 故重用石膏至 → 石膏
        (r"^自加(.+)$", r"\1"),
        (r"^再加(.+)$", r"\1"),
        (r"^加入?(.+)$", r"\1"),             # 加酸棗仁 → 酸棗仁
        (r"^方用(.+)$", r"\1"),              # 方用黃連 → 黃連
        (r"^之前(.+)$", r"\1"),              # 之前石膏 → 石膏
        (r"^合(.+)$", r"\1"),                # 合白芍 → 白芍
        (r"^故(.+)$", r"\1"),                # 故大黃 → 大黃
        (r"^(.+?)一罐$", r"\1"),             # 芒硝一罐 → 芒硝
        (r"^(.+?)加重$", r"\1"),             # 炮附子加重 → 炮附子
        (r"^(.+?)重用至$", r"\1"),           # 龍膽草重用至 → 龍膽草
    ]:
        s = re.sub(模, 替, s)
    for c in 连接词:
        s = re.sub("^" + c, "", s)
        s = re.sub(c + "$", "", s)
    s = re.sub(r"(粉|片|丸|包)$", "", s)      # 用紅棗粉 → 紅棗
    return s.strip()


def main():
    写 = "--写" in os.sys.argv
    import _抽倪剂量分布 as 剂量
    简 = 繁简()
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row

    # 白名单：问止那 85 味（已经洗过）+ 本草 453 个药名 + 上面映射表的值
    白 = {r[0] for r in con.execute("SELECT 药 FROM 剂量分布")}
    白 |= {r[0] for r in con.execute("SELECT DISTINCT 药名 FROM 本草")}
    白 |= set(映射.values()) | set(单字映射.values())
    白 = {简(x) for x in 白 if x}

    def 归一(名):
        """→ 规范药名，或 None（认不出就不写，不猜）

        ⚠️ **原样先过一遍白名单**，再谈剥连接词。否则「合欢皮」会被 `^合(.+)$` 剥成「欢皮」——
        剥词的规则天然会误伤本来合法的药名。先认原样，认得就不剥。
        """
        s0 = 简((名 or "").strip())
        if s0 in 映射:
            return 映射[s0]
        if s0 in 白:
            return s0
        s = 剥词(名)
        if not s or s in 丢弃:
            return None
        s = 简(s)
        if s in 丢弃:
            return None
        if s in 映射:
            s = 映射[s]
        if len(s) == 1 and s in 单字映射:
            s = 单字映射[s]
        s = 简(s)
        if s in 白 or len(s) >= 2 and s in 白:
            return s
        # 白名单外、但确实是两字以上的正经药名 → 也放行（本草没覆盖全）
        # ⚠️ 字符类里**不能有「药」** —— 乌药/芍药 这些正经药名会被自己拒掉（实测丢了 86 行）。
        #    只放「当连接词用」的字，它们不出现在任何药名里。
        #    `比/前/此/次/第/每/罐/粒/方` 是第二轮补的：`大黃比前方加重` 剥掉「加重」后
        #    剩「大黃比前方」，原来的字符类拦不住，于是又混进统计。
        if len(s) >= 2 and not re.search(r"[减改用为至比前此次第每罐粒方]", s):
            return s
        return None

    行 = [dict(r) for r in con.execute(
        "SELECT id,药,剂量,药_原始 FROM 处方 WHERE source='倪海厦'")]
    认, 没认 = [], Counter()
    新名 = {}
    # ⚠️ 剂量统计**必须跟归一在同一趟里做**。第一版是「先改药名、再拿 `处方.药` 重算一遍」——
    #    而没归一的那 52 行（`仁`/`骨`/`黃`）**药名没被改**，重算时照样进了统计，
    #    于是「仁 3~3 錢(n=1)」又冒了出来。**过滤条件走了两条路 = 两条路迟早不一致。**
    数, 原 = {}, defaultdict(Counter)
    for r in 行:
        n = 归一(r["药"])
        if n:
            认.append((n, r["id"], r["药"]))
            if n != r["药"]:
                新名.setdefault(n, Counter())[r["药"]] += 1
            v = 剂量.转錢(r["剂量"] or "")
            if v is not None:
                数.setdefault(n, []).append(v)
                原[n][r["药"]] += 1
        else:
            没认[r["药"]] += 1

    print("=== %s ===" % ("落库" if 写 else "干跑"))
    print("  倪案处方 %d 行" % len(行))
    print("  认得出来 %d 行（%.1f%%）" % (len(认), len(认) * 100.0 / len(行)))
    print("  认不出   %d 行（%.1f%%）—— **不写**（宁缺勿猜）"
          % (sum(没认.values()), sum(没认.values()) * 100.0 / len(行)))
    print("  认不出的前 25 个：%s"
          % "、".join("%s(%d)" % (k, v) for k, v in 没认.most_common(25)))
    print()
    print("=== 被合并的写法（前 25 组）===")
    for n, c in list(新名.items())[:25]:
        print("  %-10s ← %s" % (n, "、".join("%s×%d" % (k, v) for k, v in c.most_common())))

    if not 写:
        print("\n（干跑，没动库。加 --写 才落库。）")
        con.close()
        return

    # ── 落库 ①：改 `处方`.药，原值记进 `药_原始`（留痕、可回滚）──
    # 只处理 `药_原始 IS NULL` 的行 —— 已经改过的（问止那批）不碰。
    改 = 0
    for n, i, 原名 in 认:
        if n != 原名:
            # ⚠️ `药_原始` 用 **COALESCE** —— 这个脚本要反复跑（映射表会越补越全），
            # 写死 `药_原始=药` 的话，第二遍跑就把**已经被改过一次的名字**当成原始存进去，
            # 真原始就没了。**留痕列必须是"第一次的值"，不是"上一次的值"。**
            con.execute("UPDATE 处方 SET 药_原始=COALESCE(药_原始,药), 药=? WHERE id=?",
                        (n, i))
            改 += 1
    con.commit()
    print("\n  改 %d 行（原值已存进 `药_原始`，可回滚）" % 改)

    # ── 落库 ②：重建 `剂量_观测_倪` ──
    # 跟 `_抽倪剂量分布.py` 同一套口径：**只收能折成「錢」的**（枚/片/升/個 不收）。
    # 但**用上面同一趟算出来的 `数`**，不重读 `处方.药` —— 否则没归一的那批会混进来。
    import statistics
    con.execute("ALTER TABLE 剂量_观测_倪 ADD COLUMN 原词 TEXT") if not any(
        r[1] == "原词" for r in con.execute("PRAGMA table_info(剂量_观测_倪)")) else None
    out = []
    for 药, vs in 数.items():
        vs.sort()
        别名 = "、".join(k for k, _ in 原[药].most_common() if k != 药)
        out.append((药, len(vs), min(vs), statistics.median(vs), max(vs),
                    round(statistics.mean(vs), 2), "錢", 别名 or None))
    con.execute("DELETE FROM 剂量_观测_倪")
    con.executemany("INSERT INTO 剂量_观测_倪(药,出现次数,最小,中位,最大,均值,单位,原词)"
                    " VALUES(?,?,?,?,?,?,?,?)", out)
    con.commit()
    print("  剂量_观测_倪 重建完成：**%d 味**（原来 346 味，里面大半是垃圾）" % len(out))
    print("\n=== 重建后 top 12 ===")
    for 药, n, 小, 中, 大, u in con.execute(
            "SELECT 药,出现次数,最小,中位,最大,单位 FROM 剂量_观测_倪"
            " ORDER BY 出现次数 DESC LIMIT 12"):
        # ⚠️ 这里原来是 `% (*r[:5], r[5])`，`%s` 少了一个 → 整体错位一格，
        #    印成「2.0~5.0（中位 10.0）」= 中位比最大值还大。**数据是对的，标签在说谎。**
        print("  %-6s n=%-4d %s~%s 錢（中位 %s）" % (药, n, 小, 大, 中))
    print("\n=== 跟问止并排（`剂量_观测` 视图，两套单位，不折算）===")
    for 药 in ("桂枝", "白芍", "炙甘草", "茯苓", "白术", "细辛", "炮附子"):
        r = con.execute("SELECT source,出现次数,中位,单位 FROM 剂量_观测 WHERE 药=?"
                        " ORDER BY source", (药,)).fetchall()
        print("  %-5s %s" % (药, "　｜　".join(
            "%s: 中位%s%s (n=%s)" % (s, m, u, n) for s, n, m, u in r) if r else "（无）"))
    con.close()


if __name__ == "__main__":
    main()
